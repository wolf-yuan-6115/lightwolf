"""Regenerate the checked-in spectrum coefficients using Python's standard library."""
import math
import re
import struct
from pathlib import Path

def i0(x):
    total = term = 1.0
    for k in range(1, 80):
        term *= (x / (2 * k)) ** 2
        total += term
        if term < total * 1e-16:
            break
    return total

rust_arrays = []

def array(name, values):
    words = [struct.unpack("<I", struct.pack("<f", float(f"{v:.10e}")))[0] for v in values]
    rust_arrays.append(f"pub const {name.upper()}: [f32; {len(values)}] = [\n" + "".join(f"    f32::from_bits(0x{v:08x}),\n" for v in words) + "];\n")


firmware = Path(__file__).resolve().parents[1]
source = (firmware / 'core/src/spectrum.rs').read_text()
n = int(re.search(r'const N: usize = (\d+);', source).group(1))
assert n >= 2 and n & (n - 1) == 0, 'FFT size must be a power of two'
beta = 8.6
fir = []
for i in range(127):
    x = i - 63
    sinc = 0.5 if x == 0 else math.sin(math.pi * x / 2) / (math.pi * x)
    if x != 0 and x % 2 == 0:
        sinc = 0.0
    fir.append(sinc * i0(beta * math.sqrt(1 - (x/63)**2)) / i0(beta))
s = sum(fir)
fir = [v/s for v in fir]
array('spectrum_fir', fir)
array('spectrum_window', [0.5 - 0.5*math.cos(2*math.pi*i/n) for i in range(n)])
array('spectrum_cos', [math.cos(2*math.pi*i/n) for i in range(n//2)])
array('spectrum_sin', [-math.sin(2*math.pi*i/n) for i in range(n//2)])
array('spectrum_frequency', [20 * 1000**(i/255) for i in range(256)])

# Preserve the coefficient bits used by the compatibility corpus.
rust_path = Path(__file__).resolve().parents[1] / "core/src/spectrum_tables.rs"
rust_path.write_text("// Generated by firmware/tools/generate_spectrum_tables.py; do not edit.\n" + "".join(rust_arrays))
